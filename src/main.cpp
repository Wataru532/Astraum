// frame-rate limit for the current situation (0 = no limit beyond VSync)
int frameLimit(const App& app, bool testing) {
    if (testing) return 144;
    int user = FPS_LIMITS[std::clamp(app.fpsLimit, 0, 3)];
    if (user == 0) user = std::max(30, GetMonitorRefreshRate(GetCurrentMonitor()));
    int fps = user;
    if (app.screen != Screen::Flight) fps = std::min(fps, 60);         // menu / editors
    else if (flightPaused() || app.settingsOpen) fps = std::min(fps, 30); // nothing moves
    if (!IsWindowFocused()) fps = std::min(fps, 20);                   // window in the background
    return fps;
}

// keep the frame rate: lower the finest planet octaves while the GPU is the bottleneck and restore them
// when there is headroom. A step that does not buy frame rate is undone (the bottleneck is elsewhere,
// e.g. the limit is above what the GPU can do at any detail), so detail is never given up for nothing.
void adaptiveDetail(const App& app, int limit, float dt) {
    static float lowT = 0, highT = 0, judgeT = -1, fpsBefore = 0, coolT = 0;
    if (!app.adaptiveDetail || app.screen != Screen::Flight || flightPaused() || !IsWindowFocused()) {
        lowT = highT = 0;
        judgeT = -1;
        return;
    }
    float fps = (float)GetFPS(), gpu = gpumon::utilization();
    int d = gfx::planetDetail();
    coolT = std::max(0.0f, coolT - dt);
    if (judgeT >= 0) { // a step down was just taken: did it help?
        judgeT += dt;
        if (judgeT < 1.5f) return;
        judgeT = -1;
        if (fps < fpsBefore * 1.03f && fps < limit * 0.97f) {
            gfx::setPlanetDetail(d + 1); // no gain: undo and leave the detail alone for a while
            coolT = 30;
            return;
        }
    }
    bool gpuBusy = gpu < 0 || gpu > 85;
    if (fps < limit * 0.92f && gpuBusy && coolT <= 0) { lowT += dt; highT = 0; }
    else if (fps >= limit * 0.97f && gpu >= 0 && gpu < 70) { highT += dt; lowT = 0; }
    else lowT = highT = 0;
    if (lowT > 1.0f && d > 10) {
        fpsBefore = fps;
        gfx::setPlanetDetail(d - 1);
        lowT = 0;
        judgeT = 0;
    }
    if (highT > 4.0f && d < 16) { gfx::setPlanetDetail(d + 1); highT = 0; }
}

void fpsOverlay(const App& app) {
    static float ftMax = 0, holdT = 0;
    float ft = GetFrameTime();
    holdT += ft;
    if (ft > ftMax || holdT > 2.0f) { ftMax = ft; holdT = 0; }
    int fps = GetFPS();
    float gpu = gpumon::utilization();
    char b[160];
    int n = std::snprintf(b, sizeof b, "%d FPS  ·  %.1f ms (max %.1f)", fps, ft * 1000, ftMax * 1000);
    if (gpu >= 0) n += std::snprintf(b + n, sizeof b - n, "  ·  GPU %.0f%%", gpu);
    if (gfx::planetDetail() < 16) std::snprintf(b + n, sizeof b - n, "  ·  %s %d/16", tr("detail").c_str(), gfx::planetDetail());
    float SW = ui::SW(), SH = ui::SH();
    Vector2 m = measure(b, 13, true);
    float w = m.x + 20, h = 24, x, y;
    switch (app.screen) {
    case Screen::Flight: x = SW / 2 + 180; y = 12; break;          // right of the time-warp panel
    case Screen::Factory: x = SW - 384 - 12 - w; y = SH - 36; break; // bottom right of the 3D view
    case Screen::CAD: x = SW - 404 - 12 - w; y = SH - 36; break;
    default: x = SW - 12 - w; y = 12; break;
    }
    Color c = fps >= frameLimit(app, false) * 0.92f ? col::good : (fps >= 30 ? col::warn : col::bad);
    DrawRectangleRounded({x, y, w, h}, 0.5f, 6, Color{10, 14, 20, 200});
    text(b, x + 10, y + 4, 13, c, true);
}

void traceLog(int level, const char* fmt, va_list ap) {
    char line[256];
    static const char* names[] = {"ALL", "TRACE", "DEBUG", "INFO", "WARNING", "ERROR", "FATAL", "NONE"};
    int n = std::snprintf(line, sizeof line, "%s: ", names[std::clamp(level, 0, 7)]);
    std::vsnprintf(line + n, sizeof line - n, fmt, ap);
    crash::logLine(line);
    dbg::noteLog(line);
    if (level >= LOG_WARNING) std::fprintf(stderr, "%s\n", line);
}

// the first start after the rename: the data of the earlier name (maps, designs, settings, keys) is copied into the
// new folder; the old folder stays as it is (nothing is moved or deleted)
void migrateDataFolder(const char* appData) {
    namespace fs = std::filesystem;
    std::error_code ec;
    fs::path to = fs::path(appData) / brand::DATA_FOLDER, from = fs::path(appData) / brand::LEGACY_FOLDER;
    if (fs::exists(to, ec) || !fs::is_directory(from, ec)) return;
    fs::create_directories(to, ec);
    fs::copy(from, to, fs::copy_options::recursive | fs::copy_options::skip_existing, ec);
}

int main(int argc, char** argv) {
    {
        const char* ad = std::getenv("APPDATA");
        if (ad) migrateDataFolder(ad);
        std::string base = ad ? std::string(ad) + "\\" + brand::DATA_FOLDER : std::string(brand::DATA_FOLDER) + "Data";
        std::error_code ec;
        std::filesystem::create_directories(base, ec);
        crash::init(base + "\\crash", APP_VERSION);
    }
    bool crashTest = false, noBake = false, paced = false;
    for (int i = 1; i < argc; i++)
        if (std::strcmp(argv[i], "--crashtest") == 0) crashTest = true;
        else if (std::strcmp(argv[i], "--nobake") == 0) noBake = true;
        else if (std::strcmp(argv[i], "--paced") == 0) paced = true; // automated runs with the normal frame pacing
    crash::breadcrumb("start");
    SetTraceLogCallback(traceLog);
    SetConfigFlags(FLAG_MSAA_4X_HINT | FLAG_WINDOW_RESIZABLE | FLAG_VSYNC_HINT);
    SetTraceLogLevel(LOG_INFO); // all lines go to the crash ring buffer; warnings also to stderr
    InitWindow(1600, 900, APP_NAME);
    {
        // the window is in physical pixels: size it for the monitor's DPI and start maximised
        float dpi = std::max(1.0f, GetWindowScaleDPI().x);
        int mon = GetCurrentMonitor();
        int mw = GetMonitorWidth(mon), mh = GetMonitorHeight(mon);
        SetWindowMinSize(std::min((int)(1100 * dpi), (int)(mw * 0.6f)), std::min((int)(680 * dpi), (int)(mh * 0.6f)));
        SetWindowSize(std::min((int)(1600 * dpi), (int)(mw * 0.9f)), std::min((int)(900 * dpi), (int)(mh * 0.85f)));
        SetWindowPosition((mw - GetScreenWidth()) / 2, (mh - GetScreenHeight()) / 2);
        MaximizeWindow();
    }
    SetExitKey(0);
    SetTargetFPS(144);
    Image ic = makeIcon();
    if (ic.data) SetWindowIcon(ic);
    UnloadImage(ic);

    CATALOG.init();
    gfx::init();
    if (noBake) gfx::setBakingEnabled(false);

    // ---- the ports of the inner layers, served by the outer ones
    diag::setSink([](const char* line) { crash::breadcrumb("%s", line); });
    ground::install(&terrain::groundPort());
    {
        ports::Platform pf;
        pf.now = []() { return GetTime(); };
        pf.systemLanguage = platform::systemLanguage;
        pf.log = [](const char* line) { TraceLog(LOG_INFO, "%s", line); };
        ports::install(pf);
        ports::Presentation pr;
        pr.mapSaved = mapSavedPicture;
        pr.worldReplaced = forgetWorldView;
        pr.serviceThumbs = serviceMapPictures;
        pr.tutorialActive = []() { return tut::active(); };
        pr.stopTutorial = []() { tut::stop(); };
        ports::install(pr);
    }

    App app;
    ensureDirs(app);
    loadPrefs(app);
    keys::load(keysFile(app));
    for (int i = 1; i + 1 < argc; i++)
        if (std::strcmp(argv[i], "--fpslimit") == 0) app.fpsLimit = std::clamp(std::atoi(argv[i + 1]), 0, 3); // this run only
    ui::init(app.lang);
    ui::setTextScale(TEXT_SCALES[app.textSize]);
    ui::setUserScale(UI_SIZES[std::clamp(app.uiSize, 0, 5)]);
    nav::setReverseZoom(app.reverseZoom);
    for (int i = 1; i + 1 < argc; i++)
        if (std::strcmp(argv[i], "--sfxdump") == 0) {
            std::error_code ec;
            std::filesystem::create_directories(argv[i + 1], ec);
            int rc = sfx::dump(argv[i + 1]) ? 0 : 1;
            CloseWindow();
            return rc;
        }
    bool soundOk = sfx::init();
    crash::breadcrumb("audio: %s", soundOk ? "ok" : "no device");
    sfx::setVolume(std::clamp(app.volumePct, 0, 100) / 100.0f);
    sfx::setMusic(app.music, std::clamp(app.musicPct, 0, 100) / 100.0f);
    gfx::setTerrainQuality(app.terrainQuality);
    gfx::setDetailRange(app.detailRange / 100.0f);
    if (app.physicalShading) app.physicalShading = gfx::setPhysicalShading(true);
    ui::setClickHook([] { sfx::play(sfx::Ev::Click); });
    gpumon::start();
    Settings def;
    app.world.newGame(def);
    bool noMaps = false;
    for (int i = 1; i < argc; i++) noMaps |= std::strcmp(argv[i], "--nomaps") == 0; // comparison runs
    for (int i = 1; i + 1 < argc; i++)
        if (std::strcmp(argv[i], "--epoch") == 0) g_epochOffset = std::atof(argv[i + 1]) * 86400.0; // tests: another date
    if (!noMaps) terrain::init(app.world.U); // real surface maps of Earth, Moon and Mars (embedded)
    crash::breadcrumb("terrain maps: %zu MB", terrain::bytes() >> 20);
    app.design = builtinTemplates()[0];
    bool testing = autotestInit(app, argc, argv);
    if (testing) sfx::setVolume(0); // automated runs stay silent
    if (testing) sfx::setMusic(false, 0);
    g_prefsReadOnly = testing;     // and do not write the player's prefs (tutorial records, language)
    app.persist = !testing;        // nor maps or the last design (a test turns this on with its own folders)
    if (!testing && app.fullscreen && !IsWindowState(FLAG_BORDERLESS_WINDOWED_MODE)) ToggleBorderlessWindowed(); // (as it was left)
    else if (testing) app.fullscreen = false;
    if (!testing) {
        migrateQuicksave(app); // (the old single save becomes the first map)
        loadLastDesign(app);   // the factory shows the design used last
    }
    {
        std::string text, path;
        if (!testing && crash::pendingReport(text, path)) {
            app.crashReport = text;
            app.crashPath = path;
        }
    }
    Screen lastScreen = Screen::Menu;
    long frame = 0;

    bool quitNow = false;
    while (!quitNow) {
        // ---- quitting: the window's close button, Alt+F4 or the menu's Quit. With unsaved changes in the
        // map a dialog asks first (raylib reports the close request once per frame: it is latched here)
        bool closeReq = WindowShouldClose() || app.quit;
        app.quit = false;
        if (closeReq) {
            persistDesign(app, true);
            if (testing && !app.persist) break; // (automated runs end without asking)
            if (!mapDirty(app)) break;
            app.closeAsk = true;
        }
        frame++;
        if (app.screen != lastScreen) {
            // leaving the factory: keep its design; home screen / factory / leaving a flight: save the map
            if (lastScreen == Screen::Factory) persistDesign(app, true);
            if ((lastScreen == Screen::Flight || app.screen == Screen::Menu || app.screen == Screen::Factory) && mapDirty(app) && !tut::active())
                saveMap(app, false);
        }
        serviceSaves(app);
        if (app.screen == Screen::Factory) persistDesign(app, false); // (every 2 s, written only when it changed)
        // ---- autosave at a real-time interval (not while the active vessel is lost: that would overwrite the
        // last good state that rewind and quickload need)
        if (app.autosaveMin > 0 && !app.closeAsk && mapDirty(app) && !tut::active() && GetTime() - app.lastSaveReal > app.autosaveMin * 60.0) {
            const Vessel* av = app.world.activeVessel();
            if (av && av->destroyed) app.lastSaveReal = GetTime() - app.autosaveMin * 60.0 + 20; // (look again in 20 s)
            else saveMap(app, true);
        }
        if (app.screen != lastScreen || frame % 30 == 1) {
            static const char* names[] = {"Menu", "Factory", "Flight", "CAD"};
            if (app.screen != lastScreen) crash::breadcrumb("screen: %s", names[(int)app.screen]);
            lastScreen = app.screen;
            const Vessel* v = app.world.activeVessel();
            crash::setState("Screen: %s\nLanguage: %d, text size %d, window %dx%d\nSim time: %.1f s, warp x%g, vessels %d\nActive vessel: %s (%d comps)\nCAD craft: %d comps",
                            names[(int)app.screen], app.lang, app.textSize, GetScreenWidth(), GetScreenHeight(), app.world.t,
                            app.world.warpFactor(), (int)app.world.vessels.size(), v ? v->name.c_str() : "-", v ? (int)v->comps.size() : 0,
                            (int)app.craft.comps.size());
        }
        if (crashTest && frame == 20) crash::selfTest();
        if (mem::Pressure p = mem::update(GetTime())) {
            bool hard = p == mem::Hard;
            const mem::Status& ms = mem::status();
            crash::breadcrumb("memory pressure %s: process %zu MB, system free %zu MB", hard ? "hard" : "soft", ms.process / mem::MB,
                              ms.sysAvail / mem::MB);
            app.world.trimMemory(hard);
            trimAeroCache(hard ? 0 : mem::CACHE_BUDGET / 4);
            gfx::trimCaches(hard);
            cadTrimMemory(hard);
            mem::compactHeap();
        }
        // ---- frame pacing: nothing is drawn while minimised (the game pauses), and screens that do not
        // need full motion run slower: menu / editors 60 fps, paused flight 30, window in the background 20
        sfx::pauseMusic(IsWindowMinimized() && !testing);
        if (IsWindowMinimized() && !testing) {
            if (app.closeAsk) RestoreWindow(); // (closed from the taskbar: the question must be seen)
            sfx::setAmbient({});
            PollInputEvents();
            WaitTime(0.1);
            continue;
        }
        bool fastTest = testing && !paced;
        int limit = frameLimit(app, fastTest);
        {
            static int curFps = 144;
            if (limit != curFps) {
                SetTargetFPS(limit);
                curFps = limit;
            }
        }
        if (!fastTest) adaptiveDetail(app, limit, GetFrameTime());
        keys::newFrame();
        if (keys::pressed(keys::A::DebugScreen)) app.debugOpen = !app.debugOpen;
        if (keys::pressed(keys::A::Fullscreen)) setFullscreen(app, !app.fullscreen);
        bool wantShot = keys::pressed(keys::A::Screenshot);
        dbg::frame(GetFrameTime());
        sfx::update(GetFrameTime()); // the music
        BeginDrawing();
        gputime::setEnabled(testing || app.debugOpen); // (GPU timing only where it is shown)
        gputime::frameBegin();
        gfx::serviceBakes(); // planet field textures (outside every 3D pass)
        ui::beginFrameScale();
        ui::setBlockAll(app.closeAsk); // (the screen below the quit dialog ignores the mouse and the keys)
        keys::setSuspended(app.closeAsk);
        ui::beginFrame();
        switch (app.screen) {
        case Screen::Menu:
            app.world.refreshStates();
            menuFrame(app);
            break;
        case Screen::Factory: factoryFrame(app); break;
        case Screen::Flight: flightFrame(app); break;
        case Screen::CAD: cadFrame(app); break;
        }
        if (app.closeAsk) {
            ui::setBlockAll(false);
            ui::setInputBlocked(false);
            int c = closeDialog(app);
            if (c == 0 || c == 1) quitNow = true; // (saved in the dialog, or left as it is)
            if (c >= 0) app.closeAsk = false;
        }
        keys::setSuspended(false);
        if (wantShot) {
            // captured before the overlays, tooltip and notice are drawn
            std::string name = screenshot::capture(app.dataDir);
            app.notice = name.empty() ? tr("Screenshot skipped (still saving the previous ones)") : trf("Screenshot saved: {0}", name);
            app.noticeBad = name.empty();
            app.noticeTime = GetTime();
            sfx::play(sfx::Ev::Click);
        }
        if (int res = screenshot::takeResult(); res < 0) {
            app.notice = tr("Could not save the screenshot");
            app.noticeBad = true;
            app.noticeTime = GetTime();
        }
        if (app.debugOpen) dbg::draw(app);
        else if (app.showFps) fpsOverlay(app);
        drawNotice(app);
        ui::drawTooltip();
        if (app.screen != Screen::Flight) {
            sfx::setAmbient({}); // continuous sounds belong to the flight view
            app.world.events.clear();
        }
        if (testing && !autotestStep(app)) app.quit = true;
        gputime::frameEnd();
        EndDrawing();
    }
    finishSaves(); // (a map being written)
    finishThumbs(); // (its picture, then the GPU copies)
    screenshot::finish();
    gpumon::stop();
    sfx::shutdown();
    ui::shutdown();
    gfx::shutdown();
    CloseWindow();
    return 0;
}

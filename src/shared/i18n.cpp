std::string tr(const std::string& en) {
    if (g_lang == EN || en.empty()) return en;
    build();
    auto it = g_map.find(en);
    if (it == g_map.end()) return en;
    return g_lang == JA ? it->second->ja : it->second->de;
}

std::string trf(const std::string& en, const std::string& a, const std::string& b, const std::string& c) {
    std::string s = tr(en);
    const std::string* args[3] = {&a, &b, &c};
    for (int k = 0; k < 3; k++) {
        std::string key = "{" + std::to_string(k) + "}";
        size_t p;
        while ((p = s.find(key)) != std::string::npos) s.replace(p, key.size(), *args[k]);
    }
    return s;
}

// UTF-8 decoding of every translated string of a language (the font is made for these characters)
namespace {
void addUtf8(std::set<int>& cps, const std::string& s) {
    for (size_t i = 0; i < s.size();) {
        unsigned char c = (unsigned char)s[i];
        int cp = c, n = 1;
        if (c >= 0xF0 && i + 3 < s.size()) { cp = ((c & 0x07) << 18) | ((s[i + 1] & 0x3F) << 12) | ((s[i + 2] & 0x3F) << 6) | (s[i + 3] & 0x3F); n = 4; }
        else if (c >= 0xE0 && i + 2 < s.size()) { cp = ((c & 0x0F) << 12) | ((s[i + 1] & 0x3F) << 6) | (s[i + 2] & 0x3F); n = 3; }
        else if (c >= 0xC0 && i + 1 < s.size()) { cp = ((c & 0x1F) << 6) | (s[i + 1] & 0x3F); n = 2; }
        else if (c >= 0x80) cp = 0x3F; // (a stray byte: '?')
        cps.insert(cp);
        i += n;
    }
}
} // namespace

std::vector<int> codepoints(int l) {
    std::set<int> cps;
    for (int c = 32; c < 127; c++) cps.insert(c);
    for (int c = 160; c < 256; c++) cps.insert(c);
    for (int c : {8211, 8212, 8226, 8592, 8593, 8594, 8595, 8734, 8722, 8467}) cps.insert(c);
    for (int c = 913; c <= 969; c++) cps.insert(c); // Greek
    if (l != EN) {
        for (const E& e : TABLE) addUtf8(cps, l == JA ? e.ja : e.de);
        if (l == JA) addUtf8(cps, "日本語DeutschEnglish、。・「」（）：！？ー");
    }
    // native language names are always shown in the language picker
    addUtf8(cps, "日本語");
    return std::vector<int>(cps.begin(), cps.end());
}


"""Rasterise assets/icon.svg into the Windows .ico, PNG previews and the embedded window-icon header.

Usage:  python tools/make_icon.py
Needs:  Microsoft Edge (headless SVG renderer) and Pillow.
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "assets" / "icon.svg"
SVG_SMALL = ROOT / "assets" / "icon_small.svg"  # used for 16-24 px
SMALL_MAX = 24
ICO = ROOT / "assets" / "icon.ico"
PNG = ROOT / "assets" / "icon_256.png"
HEADER = ROOT / "src" / "icon_png.hpp"
RENDER = 1024
ICO_SIZES = [16, 20, 24, 32, 40, 48, 64, 96, 128, 256]

EDGE_CANDIDATES = [
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
]


def render_svg(svg: Path, out_png: Path) -> None:
    edge = next((p for p in EDGE_CANDIDATES if os.path.exists(p)), None)
    if edge is None:
        sys.exit("Microsoft Edge not found")
    with tempfile.TemporaryDirectory() as tmp:
        html = Path(tmp) / "icon.html"
        html.write_text(
            "<!doctype html><html><head><style>html,body{margin:0;padding:0;background:transparent;overflow:hidden}"
            f"img{{display:block;width:{RENDER}px;height:{RENDER}px}}</style></head>"
            f"<body><img src='{svg.as_uri()}'></body></html>",
            encoding="utf-8",
        )
        for attempt in range(3):
            r = subprocess.run(
                [edge, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                 "--no-first-run", "--disable-extensions", "--virtual-time-budget=2000",
                 "--default-background-color=00000000", f"--window-size={RENDER},{RENDER}",
                 f"--user-data-dir={Path(tmp) / f'profile{attempt}'}", f"--screenshot={out_png}", html.as_uri()],
                capture_output=True, timeout=120,
            )
            if out_png.exists():
                return
        sys.exit(f"Edge did not produce a screenshot for {svg.name}:\n{r.stderr.decode(errors='replace')[-2000:]}")


def main() -> None:
    def load(svg: Path) -> Image.Image:
        with tempfile.TemporaryDirectory() as tmp:
            raw = Path(tmp) / "raw.png"
            render_svg(svg, raw)
            im = Image.open(raw).convert("RGBA")
            im.load()
        return im.crop((0, 0, RENDER, RENDER)) if im.size != (RENDER, RENDER) else im

    img = load(SVG)
    small_src = load(SVG_SMALL)
    img.resize((256, 256), Image.Resampling.LANCZOS).save(PNG)
    frames = [(small_src if s <= SMALL_MAX else img).resize((s, s), Image.Resampling.LANCZOS) for s in ICO_SIZES]
    frames[-1].save(ICO, format="ICO", sizes=[(s, s) for s in ICO_SIZES], append_images=frames[:-1])
    # 64 px PNG embedded in the executable for the window/taskbar icon
    small = Path(tempfile.gettempdir()) / "astraum_icon64.png"
    img.resize((64, 64), Image.Resampling.LANCZOS).save(small, optimize=True)
    data = small.read_bytes()
    small.unlink()
    lines = ["// Generated by tools/make_icon.py from assets/icon.svg - do not edit", "#pragma once",
             f"static const unsigned int ICON_PNG_SIZE = {len(data)};",
             "static const unsigned char ICON_PNG[] = {"]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    lines.append("};")
    HEADER.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {ICO.name} ({', '.join(map(str, ICO_SIZES))}), {PNG.name}, {HEADER.name} ({len(data)} bytes)")


if __name__ == "__main__":
    main()

def strip_comment(line: str) -> str:
    """Removes a C comment prefix ('// ', ' * ', '** ') from one line."""
    return re.sub(r"^\s*(/\*|//|\*\*|\*)\s?", "", line.rstrip()).expandtabs(4)


def block(path: pathlib.Path, start: str, end: str) -> str:
    """The lines from the first one containing `start` to the next one containing `end`."""
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    for i, line in enumerate(lines):
        if start in line:
            for j in range(i, len(lines)):
                if end in lines[j]:
                    text = [strip_comment(l) for l in lines[i:j + 1]]
                    return "\n".join(text).strip()
            break
    raise SystemExit(f"licence text not found in {path.name}: {start!r} .. {end!r}")


def first_line(path: pathlib.Path, pattern: str) -> str:
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if re.search(pattern, line):
            return strip_comment(line).strip()
    raise SystemExit(f"{pattern!r} not found in {path.name}")


def section(title: str, note: str, text: str) -> str:
    head = f"{RULE}\n{title}\n{RULE}\n"
    if note:
        head += note.strip() + "\n\n"
    return head + text.strip() + "\n"


